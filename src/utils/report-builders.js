import { calculateScore, countsBySeverity, scoreLabel, cvssScore } from '@/utils/scoring.js';

export function buildMarkdownReport(result, groups, score) {
  const { owner, repo, workflows, findings, scannedAt } = result;
  const counts = countsBySeverity(findings);
  const label  = scoreLabel(score);

  let md = `# GitHub Actions Security Report\n\n`;
  md += `**Repository:** \`${owner}/${repo}\`  \n`;
  md += `**Scanned:** ${new Date(scannedAt).toLocaleString()}  \n`;
  md += `**Workflows analysed:** ${workflows.length}  \n`;
  md += `**Risk Score:** ${score.toFixed(1)} / 10.0 (${label})  \n`;
  md += `**Total findings:** ${findings.length}\n\n`;

  if (findings.length === 0) {
    md += `No security issues were detected. Manual review is still recommended.\n`;
    return md;
  }

  md += `## Summary\n\n`;
  md += `| Severity | Count |\n|:---|:---|\n`;
  if (counts.critical > 0) md += `| Critical | ${counts.critical} |\n`;
  if (counts.high     > 0) md += `| High     | ${counts.high}     |\n`;
  if (counts.medium   > 0) md += `| Medium   | ${counts.medium}   |\n`;
  if (counts.low      > 0) md += `| Low      | ${counts.low}      |\n`;
  md += `\n---\n\n## Findings\n\n`;

  for (const group of groups) {
    const rep    = group.findings[0];
    const s      = rep.cvss?.score ?? cvssScore(group.severity);
    const occStr = group.findings.length > 1
      ? ` (${group.findings.length} occurrences)`
      : '';

    md += `### [${group.severity.toUpperCase()}] ${group.title}\n\n`;
    md += `**File:** \`${rep.file}${rep.line ? `:${rep.line}` : ''}\`${occStr}  \n`;

    const rows = [];
    if (s)              rows.push(`| CVSS Score    | ${s.toFixed(1)} |`);
    if (rep.cvss?.vector) rows.push(`| CVSS Vector   | \`${rep.cvss.vector}\` |`);
    if (rep.cvss?.cwe)  rows.push(`| CWE           | [${rep.cvss.cwe}](https://cwe.mitre.org/data/definitions/${rep.cvss.cwe.replace('CWE-', '')}.html) |`);
    if (rep.cvss?.cve?.length) rows.push(`| CVE           | ${rep.cvss.cve.map(id => `[${id}](https://nvd.nist.gov/vuln/detail/${id})`).join(', ')} |`);
    if (rep.owasp)      rows.push(`| OWASP CI/CD   | ${rep.owasp} |`);
    if (rep.confidence) rows.push(`| Confidence    | ${rep.confidence} |`);
    if (rows.length) {
      md += `\n| Attribute | Value |\n|:---|:---|\n`;
      md += rows.join('\n') + '\n';
    }

    if (rep.detail)      md += `\n**Description:**  \n${rep.detail}\n`;
    if (rep.exploit)     md += `\n**Exploit Scenario:**  \n${rep.exploit}\n`;
    if (rep.remediation) md += `\n**Remediation:**\n\`\`\`\n${rep.remediation}\n\`\`\`\n`;

    if (group.findings.length > 1) {
      md += `\n**Additional occurrences:**\n`;
      group.findings.slice(1).forEach(f => {
        md += `- \`${f.file}${f.line ? `:${f.line}` : ''}\`${f.context ? ` — ${f.context}` : ''}\n`;
      });
    }

    md += `\n---\n\n`;
  }

  md += `*Report generated by [PWNPipe](https://github.com) — ${new Date().toISOString()}*\n`;
  md += `*Only scan repositories you own or have explicit permission to test.*\n`;
  return md;
}

// SARIF 2.1.0 — https://docs.oasis-open.org/sarif/sarif/v2.1.0/sarif-v2.1.0.html
export function buildSarif(result, groups) {
  const { owner, repo } = result;
  const LEVEL_MAP = { critical: 'error', high: 'error', medium: 'warning', low: 'note' };

  const rulesSeen = new Map();
  for (const g of groups) {
    if (rulesSeen.has(g.rule)) continue;
    const rep = g.findings[0];
    rulesSeen.set(g.rule, {
      id:               g.rule,
      name:             g.rule.split('-').map(w => w[0].toUpperCase() + w.slice(1)).join(''),
      shortDescription: { text: g.title },
      fullDescription:  { text: rep.detail ?? g.title },
      helpUri:          rep.cvss?.cwe
        ? `https://cwe.mitre.org/data/definitions/${rep.cvss.cwe.replace('CWE-', '')}.html`
        : 'https://owasp.org/www-project-top-10-ci-cd-security-risks/',
      properties: {
        tags:               ['security', 'github-actions', rep.owasp ?? ''].filter(Boolean),
        'security-severity': String(rep.cvss?.score ?? 5.0),
        precision:           rep.confidence === 'CONFIRMED' || rep.confidence === 'HIGH' ? 'high' : 'medium',
      },
    });
  }

  const sarifResults = [];
  for (const g of groups) {
    for (const f of g.findings) {
      sarifResults.push({
        ruleId:  f.rule,
        level:   LEVEL_MAP[g.severity] ?? 'warning',
        message: { text: f.detail ?? f.title },
        locations: [{
          physicalLocation: {
            artifactLocation: { uri: f.file, uriBaseId: '%SRCROOT%' },
            region: f.line ? { startLine: f.line } : undefined,
          },
        }],
        properties: {
          confidence: f.confidence ?? 'MEDIUM',
          owasp:      f.owasp ?? null,
          cvss:       f.cvss?.score ?? null,
          cve:        f.cvss?.cve ?? [],
        },
      });
    }
  }

  return {
    $schema: 'https://raw.githubusercontent.com/oasis-tcs/sarif-spec/master/Schemata/sarif-schema-2.1.0.json',
    version: '2.1.0',
    runs: [{
      tool: {
        driver: {
          name:           'PWNPipe',
          version:        '1.0.0',
          informationUri: 'https://github.com',
          rules:          [...rulesSeen.values()],
        },
      },
      results:    sarifResults,
      properties: { repository: `${owner}/${repo}`, scannedAt: result.scannedAt },
    }],
  };
}

export function buildCsv(groups) {
  const esc = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;
  const header = ['Severity','CVSS Score','Confidence','OWASP','CWE','CVE','Rule','Title','File','Line','Context','Description','Impact'];
  const rows = [header.join(',')];
  for (const g of groups) {
    for (const f of g.findings) {
      rows.push([
        esc(g.severity.toUpperCase()),
        esc((f.cvss?.score ?? cvssScore(g.severity)).toFixed(1)),
        esc(f.confidence ?? ''),
        esc(f.owasp ?? ''),
        esc(f.cvss?.cwe ?? ''),
        esc((f.cvss?.cve ?? []).join('; ')),
        esc(f.rule),
        esc(f.title),
        esc(f.file),
        esc(f.line ?? ''),
        esc(f.context ?? ''),
        esc(f.detail ?? ''),
        esc(f.impact ?? ''),
      ].join(','));
    }
  }
  return rows.join('\n');
}

export function download(filename, content, mime) {
  const blob = new Blob([content], { type: mime });
  const url  = URL.createObjectURL(blob);
  const a    = Object.assign(document.createElement('a'), { href: url, download: filename });
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

// ── Canvas helpers ────────────────────────────────────────────────────────────

function rr(ctx, x, y, w, h, r) {
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.lineTo(x + w - r, y);
  ctx.quadraticCurveTo(x + w, y, x + w, y + r);
  ctx.lineTo(x + w, y + h - r);
  ctx.quadraticCurveTo(x + w, y + h, x + w - r, y + h);
  ctx.lineTo(x + r, y + h);
  ctx.quadraticCurveTo(x, y + h, x, y + h - r);
  ctx.lineTo(x, y + r);
  ctx.quadraticCurveTo(x, y, x + r, y);
  ctx.closePath();
}

const CANVAS_COLORS = {
  bg: '#0a0a0a', surface: '#111', border: '#222',
  text: '#f0f0f0', muted: '#555', sub: '#888',
  critical: '#dc2626', high: '#f97316', medium: '#eab308', low: '#22c55e',
};

function scoreColor(score) {
  if (score >= 9.0) return CANVAS_COLORS.critical;
  if (score >= 7.0) return CANVAS_COLORS.high;
  if (score >= 4.0) return CANVAS_COLORS.medium;
  return CANVAS_COLORS.low;
}

export function generateSummaryCard(result, groups, score) {
  const { owner, repo, findings, workflows, scannedAt } = result;
  const counts = countsBySeverity(findings);
  const label  = scoreLabel(score);
  const C      = CANVAS_COLORS;
  const scoreC = scoreColor(score);

  const W = 900, H = 500, SC = 2;
  const canvas = document.createElement('canvas');
  canvas.width  = W * SC;
  canvas.height = H * SC;
  const ctx = canvas.getContext('2d');
  ctx.scale(SC, SC);

  // Background + grid
  ctx.fillStyle = C.bg;
  ctx.fillRect(0, 0, W, H);
  ctx.strokeStyle = '#151515'; ctx.lineWidth = 1;
  for (let x = 0; x <= W; x += 40) { ctx.beginPath(); ctx.moveTo(x, 0); ctx.lineTo(x, H); ctx.stroke(); }
  for (let y = 0; y <= H; y += 40) { ctx.beginPath(); ctx.moveTo(0, y); ctx.lineTo(W, y); ctx.stroke(); }

  // Left panel
  ctx.fillStyle = C.surface;
  rr(ctx, 24, 24, 410, H - 48, 12); ctx.fill();
  ctx.strokeStyle = C.border; ctx.lineWidth = 1;
  rr(ctx, 24, 24, 410, H - 48, 12); ctx.stroke();

  ctx.font = 'bold 12px monospace'; ctx.fillStyle = scoreC;
  ctx.fillText('PWNPipe · GitHub Actions Security Scanner', 44, 54);

  ctx.strokeStyle = C.border; ctx.lineWidth = 1;
  ctx.beginPath(); ctx.moveTo(44, 64); ctx.lineTo(414, 64); ctx.stroke();

  ctx.font = 'bold 22px monospace'; ctx.fillStyle = C.muted;
  const ownerW = ctx.measureText(`${owner}/`).width;
  ctx.fillText(`${owner}/`, 44, 100);
  ctx.fillStyle = C.text;
  ctx.fillText(repo.length > 22 ? repo.slice(0, 20) + '…' : repo, 44 + ownerW, 100);

  ctx.font = '11px monospace'; ctx.fillStyle = C.muted;
  ctx.fillText(`${workflows.length} workflow${workflows.length !== 1 ? 's' : ''} · ${findings.length} finding${findings.length !== 1 ? 's' : ''}`, 44, 122);

  const sevs = [
    { key: 'critical', color: C.critical },
    { key: 'high',     color: C.high },
    { key: 'medium',   color: C.medium },
    { key: 'low',      color: C.low },
  ];
  const maxC = Math.max(1, ...sevs.map(s => counts[s.key]));
  const BAR_MAX = 195, BAR_H = 12, START_X = 145, LABEL_X = 44, START_Y = 152, GAP = 38;

  sevs.forEach(({ key, color }, i) => {
    const y = START_Y + i * GAP;
    const count = counts[key];

    ctx.fillStyle = color;
    ctx.beginPath(); ctx.arc(LABEL_X + 4, y + 8, 4, 0, Math.PI * 2); ctx.fill();

    ctx.font = '10px monospace'; ctx.fillStyle = C.muted;
    ctx.fillText(key.toUpperCase(), LABEL_X + 14, y + 12);

    ctx.fillStyle = C.border;
    rr(ctx, START_X, y + 2, BAR_MAX, BAR_H, 4); ctx.fill();

    if (count > 0) {
      ctx.fillStyle = color; ctx.shadowColor = color; ctx.shadowBlur = 6;
      rr(ctx, START_X, y + 2, Math.max(8, (count / maxC) * BAR_MAX), BAR_H, 4); ctx.fill();
      ctx.shadowBlur = 0;
    }

    ctx.font = 'bold 11px monospace'; ctx.fillStyle = count > 0 ? color : C.muted;
    ctx.fillText(String(count), START_X + BAR_MAX + 10, y + 12);
  });

  const TOP_Y = 320;
  ctx.strokeStyle = C.border; ctx.lineWidth = 1;
  ctx.beginPath(); ctx.moveTo(44, TOP_Y - 8); ctx.lineTo(414, TOP_Y - 8); ctx.stroke();
  ctx.font = 'bold 9px monospace'; ctx.fillStyle = C.muted;
  ctx.fillText('TOP FINDINGS', 44, TOP_Y + 6);
  groups.slice(0, 3).forEach((g, i) => {
    const y = TOP_Y + 26 + i * 22;
    const fc = g.severity === 'critical' ? C.critical : g.severity === 'high' ? C.high : g.severity === 'medium' ? C.medium : C.low;
    ctx.fillStyle = fc; ctx.font = 'bold 9px monospace';
    ctx.fillText(g.severity.toUpperCase(), 44, y);
    const sw = ctx.measureText(g.severity.toUpperCase()).width;
    ctx.fillStyle = C.text; ctx.font = '11px monospace';
    ctx.fillText(g.title.length > 46 ? g.title.slice(0, 44) + '…' : g.title, 44 + sw + 8, y);
  });
  if (findings.length === 0) {
    ctx.font = '12px monospace'; ctx.fillStyle = C.low;
    ctx.fillText('No security issues detected.', 44, TOP_Y + 30);
  }

  ctx.font = '10px monospace'; ctx.fillStyle = C.muted;
  ctx.fillText(new Date(scannedAt).toLocaleString(), 44, H - 34);

  // Right panel: CVSS gauge
  const GX = 670, GY = 220, GR = 105;
  const startA = Math.PI * 0.75, sweep = Math.PI * 1.5;

  ctx.strokeStyle = C.border; ctx.lineWidth = 14; ctx.lineCap = 'round';
  ctx.beginPath(); ctx.arc(GX, GY, GR, startA, startA + sweep); ctx.stroke();

  [[4 / 10, C.medium], [7 / 10, C.high], [9 / 10, C.critical]].forEach(([at, tc]) => {
    const angle = startA + at * sweep;
    ctx.strokeStyle = tc; ctx.lineWidth = 2; ctx.globalAlpha = 0.5;
    ctx.beginPath();
    ctx.moveTo(GX + (GR - 10) * Math.cos(angle), GY + (GR - 10) * Math.sin(angle));
    ctx.lineTo(GX + (GR + 10) * Math.cos(angle), GY + (GR + 10) * Math.sin(angle));
    ctx.stroke(); ctx.globalAlpha = 1;
  });

  if (score > 0) {
    ctx.strokeStyle = scoreC; ctx.lineWidth = 14; ctx.shadowColor = scoreC; ctx.shadowBlur = 14;
    ctx.beginPath(); ctx.arc(GX, GY, GR, startA, startA + (score / 10) * sweep); ctx.stroke();
    ctx.shadowBlur = 0;
  }

  ctx.font = 'bold 52px monospace'; ctx.fillStyle = scoreC;
  ctx.shadowColor = scoreC; ctx.shadowBlur = 20;
  ctx.textAlign = 'center'; ctx.fillText(score.toFixed(1), GX, GY + 20); ctx.shadowBlur = 0;

  ctx.font = '11px monospace'; ctx.fillStyle = C.muted;
  ctx.fillText('CVSS / 10.0', GX, GY + 44);

  ctx.font = 'bold 15px monospace'; ctx.fillStyle = scoreC;
  ctx.shadowColor = scoreC; ctx.shadowBlur = 10;
  ctx.fillText(label, GX, GY + 70); ctx.shadowBlur = 0;
  ctx.textAlign = 'left';

  ctx.strokeStyle = C.border; ctx.lineWidth = 1;
  rr(ctx, 462, 24, W - 462 - 24, H - 48, 12); ctx.stroke();

  return canvas;
}

export function generateDetailedCard(result, groups, score) {
  const { owner, repo, findings, workflows, scannedAt } = result;
  const label  = scoreLabel(score);
  const counts = countsBySeverity(findings);
  const C      = { ...CANVAS_COLORS, border: '#1e1e1e' };
  const scoreC = scoreColor(score);

  const W = 1000, ROW_H = 48, HEADER_H = 200;
  const H = HEADER_H + groups.length * ROW_H + 60;
  const SC = 2;

  const canvas = document.createElement('canvas');
  canvas.width  = W * SC;
  canvas.height = H * SC;
  const ctx = canvas.getContext('2d');
  ctx.scale(SC, SC);

  ctx.fillStyle = C.bg; ctx.fillRect(0, 0, W, H);

  ctx.fillStyle = C.surface; ctx.fillRect(0, 0, W, HEADER_H);
  ctx.strokeStyle = C.border; ctx.lineWidth = 1;
  ctx.beginPath(); ctx.moveTo(0, HEADER_H); ctx.lineTo(W, HEADER_H); ctx.stroke();

  ctx.font = 'bold 11px monospace'; ctx.fillStyle = scoreC;
  ctx.fillText('PWNPipe · GitHub Actions Security Scanner', 32, 36);
  ctx.font = 'bold 24px monospace'; ctx.fillStyle = C.muted;
  const ow = ctx.measureText(`${owner}/`).width;
  ctx.fillText(`${owner}/`, 32, 74);
  ctx.fillStyle = C.text;
  ctx.fillText(repo.length > 28 ? repo.slice(0, 26) + '…' : repo, 32 + ow, 74);
  ctx.font = '11px monospace'; ctx.fillStyle = C.muted;
  ctx.fillText(`${workflows.length} workflows · ${findings.length} findings · ${new Date(scannedAt).toLocaleString()}`, 32, 96);

  const chipX = W - 200;
  ctx.font = 'bold 40px monospace'; ctx.fillStyle = scoreC;
  ctx.shadowColor = scoreC; ctx.shadowBlur = 16;
  ctx.textAlign = 'center'; ctx.fillText(score.toFixed(1), chipX, 66); ctx.shadowBlur = 0;
  ctx.font = '11px monospace'; ctx.fillStyle = C.muted; ctx.fillText('CVSS / 10.0', chipX, 84);
  ctx.font = 'bold 12px monospace'; ctx.fillStyle = scoreC; ctx.fillText(label, chipX, 100);
  ctx.textAlign = 'left';

  const sevs = [
    { key: 'critical', color: C.critical },
    { key: 'high',     color: C.high },
    { key: 'medium',   color: C.medium },
    { key: 'low',      color: C.low },
  ];
  const SY = 130;
  sevs.forEach(({ key, color }, i) => {
    const x = 32 + i * 130;
    const count = counts[key];
    ctx.fillStyle = color;
    ctx.beginPath(); ctx.arc(x + 5, SY + 8, 5, 0, Math.PI * 2); ctx.fill();
    ctx.font = '10px monospace'; ctx.fillStyle = C.muted;
    ctx.fillText(key.toUpperCase(), x + 15, SY + 12);
    ctx.font = 'bold 20px monospace'; ctx.fillStyle = count > 0 ? color : C.muted;
    ctx.fillText(String(count), x + 5, SY + 38);
  });

  const colY = HEADER_H + 20;
  ctx.fillStyle = C.border; ctx.fillRect(0, HEADER_H + 28, W, 1);
  ctx.font = 'bold 9px monospace'; ctx.fillStyle = C.muted;
  ctx.fillText('SEVERITY', 32, colY); ctx.fillText('CVSS', 132, colY);
  ctx.fillText('FINDING', 186, colY); ctx.fillText('FILE', W - 300, colY);
  ctx.fillText('OWASP', W - 100, colY);

  groups.forEach((g, i) => {
    const rep  = g.findings[0];
    const rowY = HEADER_H + 40 + i * ROW_H;
    const fc   = g.severity === 'critical' ? C.critical : g.severity === 'high' ? C.high : g.severity === 'medium' ? C.medium : C.low;
    const s    = rep.cvss?.score ?? cvssScore(g.severity);

    if (i % 2 === 0) { ctx.fillStyle = 'rgba(255,255,255,0.02)'; ctx.fillRect(0, rowY - 4, W, ROW_H); }

    ctx.fillStyle = fc; ctx.fillRect(0, rowY - 4, 3, ROW_H);

    ctx.fillStyle = fc + '22';
    rr(ctx, 32, rowY + 2, 82, 18, 4); ctx.fill();
    ctx.fillStyle = fc; ctx.font = 'bold 9px monospace';
    ctx.textAlign = 'center'; ctx.fillText(g.severity.toUpperCase(), 73, rowY + 14); ctx.textAlign = 'left';

    ctx.font = 'bold 13px monospace'; ctx.fillStyle = fc;
    ctx.fillText(s.toFixed(1), 132, rowY + 16);

    ctx.font = '12px monospace'; ctx.fillStyle = C.text;
    const maxTitleW = W - 186 - 320;
    let title = g.title;
    while (ctx.measureText(title).width > maxTitleW && title.length > 10) title = title.slice(0, -1);
    if (title.length < g.title.length) title += '…';
    ctx.fillText(title, 186, rowY + 16);

    if (g.findings.length > 1) {
      const tw = ctx.measureText(title).width;
      ctx.font = '9px monospace'; ctx.fillStyle = C.muted;
      ctx.fillText(`×${g.findings.length}`, 186 + tw + 6, rowY + 16);
    }

    ctx.font = '10px monospace'; ctx.fillStyle = C.muted;
    const fileStr = `${rep.file}${rep.line ? `:${rep.line}` : ''}`;
    ctx.fillText(fileStr.length > 36 ? '…' + fileStr.slice(-34) : fileStr, W - 300, rowY + 16);

    if (rep.owasp) {
      ctx.fillStyle = '#7c3aed22';
      rr(ctx, W - 108, rowY + 4, 78, 16, 3); ctx.fill();
      ctx.fillStyle = '#a78bfa'; ctx.font = 'bold 9px monospace';
      ctx.textAlign = 'center'; ctx.fillText(rep.owasp, W - 69, rowY + 15); ctx.textAlign = 'left';
    }

    ctx.strokeStyle = C.border; ctx.lineWidth = 0.5;
    ctx.beginPath(); ctx.moveTo(0, rowY + ROW_H - 4); ctx.lineTo(W, rowY + ROW_H - 4); ctx.stroke();
  });

  const FY = HEADER_H + 40 + groups.length * ROW_H + 20;
  ctx.fillStyle = C.border; ctx.fillRect(0, FY - 8, W, 1);
  ctx.font = '10px monospace'; ctx.fillStyle = C.muted;
  ctx.fillText(`Generated by PWNPipe · ${new Date().toISOString()}`, 32, FY + 12);
  ctx.fillStyle = scoreC; ctx.font = 'bold 10px monospace';
  ctx.textAlign = 'right';
  ctx.fillText('Only scan repos you own or have permission to test.', W - 32, FY + 12);
  ctx.textAlign = 'left';

  return canvas;
}
